function protectPlaceholders(text) {
  const placeholders = [];
  const protectedText = text.replace(/{{[^}]+}}/g, (match) => {
    const token = `__PH_${placeholders.length}__`;
    placeholders.push(match);
    return token;
  });
  return [protectedText, placeholders];
}

function restorePlaceholders(text, placeholders) {
  return placeholders.reduce((acc, value, index) => acc.replaceAll(`__PH_${index}__`, value), text);
}

function translateString(value, lang) {
  const direct = exact[lang][value];
  if (direct != null) return direct;

  const [protectedValue, placeholders] = protectPlaceholders(value);
  let translated = protectedValue;
  for (const [source, target] of wordMaps[lang]) {
    translated = translated.replace(new RegExp(`\\b${source}\\b`, 'gi'), target);
  }
  return restorePlaceholders(translated, placeholders);
}

function translateNode(value, lang) {
  if (typeof value === 'string') return translateString(value, lang);
  if (Array.isArray(value)) return value.map((item) => translateNode(item, lang));
  if (value != null && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, child]) => [key, translateNode(child, lang)]),
    );
  }
  return value;
}

for (const [source, target, lang] of files) {
  const data = JSON.parse(fs.readFileSync(source, 'utf8'));
  const translated = translateNode(data, lang);
  fs.writeFileSync(target, `${JSON.stringify(translated, null, 2)}\n`);
}
